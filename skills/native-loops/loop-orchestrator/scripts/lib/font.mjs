// Characters the loops write that have a plain stand-in.
const STAND_INS = { '—': '-', '–': '-', '−': '-', '‘': "'", '’': "'", '“': '"', '”': '"', '…': '...', '•': '·', '×': 'x', '\t': ' ', '\n': ' ', '\r': ' ', '\u00a0': ' ' };

/** One cell: 5 columns plus 1 of space; 9 rows (7 above the baseline, 2 below) plus 2 of leading. */
export const CELL = Object.freeze({ width: 6, height: 11, ink: 9 });

/** The text with every character the font cannot draw folded to one it can, or `?`. */
export function normalizeText(text) {
  let out = '';
  for (const char of String(text ?? '')) {
    if (GLYPHS[char]) { out += char; continue; }
    if (STAND_INS[char] !== undefined) { out += STAND_INS[char]; continue; }
    const folded = char.normalize('NFKD').replace(/[̀-ͯ]/gu, '');
    out += [...folded].every((part) => GLYPHS[part]) && folded ? folded : '?';
  }
  return out;
}

export function textWidth(text, scale = 1) {
  const length = [...normalizeText(text)].length;
  return length ? (length * CELL.width - 1) * scale : 0;
}

export const lineHeight = (scale = 1) => CELL.height * scale;

/** Draw the text with its top-left at (x, y); pixels outside the image are skipped. Returns the width drawn. */
export function drawText(image, text, x, y, { scale = 1, color = [0, 0, 0, 255] } = {}) {
  const [red, green, blue, alpha = 255] = color;
  const start = Math.round(x);
  let left = start;
  const top = Math.round(y);
  for (const char of normalizeText(text)) {
    const rows = GLYPHS[char] ?? GLYPHS['?'];
    rows.forEach((bits, row) => {
      for (let col = 0; col < 5; col += 1) {
        if (!(bits & (16 >> col))) continue;
        for (let dy = 0; dy < scale; dy += 1) {
          const py = top + row * scale + dy;
          if (py < 0 || py >= image.height) continue;
          for (let dx = 0; dx < scale; dx += 1) {
            const px = left + col * scale + dx;
            if (px < 0 || px >= image.width) continue;
            const offset = (py * image.width + px) * 4;
            image.data[offset] = red; image.data[offset + 1] = green; image.data[offset + 2] = blue; image.data[offset + 3] = alpha;
          }
        }
      }
    });
    left += CELL.width * scale;
  }
  return left > start ? left - start - scale : 0;
}

/** Lines no wider than maxWidth at this scale, broken at spaces; a word longer than a line is cut. */
export function wrapText(text, maxWidth, scale = 1) {
  const perLine = Math.max(1, Math.floor((maxWidth / scale + 1) / CELL.width));
  const lines = [];
  let line = '';
  for (const word of normalizeText(text).split(' ').filter(Boolean)) {
    let rest = word;
    while (rest.length > perLine) {
      if (line) { lines.push(line); line = ''; }
      lines.push(rest.slice(0, perLine));
      rest = rest.slice(perLine);
    }
    if (!line) line = rest;
    else if (line.length + 1 + rest.length <= perLine) line += ` ${rest}`;
    else { lines.push(line); line = rest; }
  }
  if (line) lines.push(line);
  return lines;
}
